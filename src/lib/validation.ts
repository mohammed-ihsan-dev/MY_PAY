import { z } from "zod";
import { isValidDateKey, MONTH_RE } from "./dates";
import { DEDUCTION_CATEGORIES, EXPENSE_CATEGORIES, INCOME_CATEGORIES } from "./types";

// Shared by client forms and server route handlers (single source of truth).
// Amounts are entered in RUPEES (max 2 decimals) and converted to paise on the server.

export const monthSchema = z.string().regex(MONTH_RE, { error: "Month must be YYYY-MM" });
export const dateKeySchema = z.string().refine(isValidDateKey, { error: "Enter a valid date" });

export const rupeeAmountSchema = z.coerce
  .number({ error: "Enter an amount" })
  .positive({ error: "Amount must be greater than zero" })
  .max(100_000_000, { error: "Amount is too large" })
  .refine((v) => Math.abs(Math.round(v * 100) - v * 100) < 1e-6, { error: "At most 2 decimal places" });

const optionalText = (max: number) => z.string().trim().max(max).optional().default("");
/** Random id generated by the form so a double-tap or retry never records the same thing twice. */
const requestIdSchema = z.string().regex(/^[A-Za-z0-9-]{8,64}$/).optional();

export const loginSchema = z.object({
  password: z.string().min(1, { error: "Enter your password" }).max(200),
});

export const changePasswordSchema = z
  .object({
    currentPassword: z.string().min(1).max(200),
    newPassword: z.string().min(4, { error: "Use at least 4 characters" }).max(200),
  })
  .refine((v) => v.currentPassword !== v.newPassword, { error: "New password must differ", path: ["newPassword"] });

export const settingsInputSchema = z.object({
  monthlyBasicSalary: z.coerce.number({ error: "Enter your salary" }).min(0).max(100_000_000),
  salaryDivisor: z.coerce.number().int({ error: "Whole days only" }).min(1).max(31),
  standardDailyHours: z.coerce.number().min(0.5).max(24),
  overtimeMultiplier: z.coerce.number().min(0).max(10),
  paydayDay: z.coerce.number().int().min(1).max(28),
  timezone: z.string().refine(
    (tz) => {
      try {
        new Intl.DateTimeFormat("en-US", { timeZone: tz });
        return true;
      } catch {
        return false;
      }
    },
    { error: "Unknown timezone" }
  ),
});
export type SettingsInput = z.infer<typeof settingsInputSchema>;

// Salary cycle entry: raw text inputs; the server parses and recalculates.
export const salaryCycleInputSchema = z.object({
  basicSalary: z.string().trim().max(20),
  workingHours: z.coerce.number().int().min(0).max(744).optional().default(0),
  workingMinutes: z.coerce.number().int().min(0).max(59, { error: "Minutes must be 0–59" }).optional().default(0),
  overtime: z.string().trim().max(20).optional().default(""),
  notes: optionalText(300),
});

// Only the finalized "final salary payable" is ever credited, so no amount is taken here.
export const receiveSalarySchema = z.object({
  receivedOn: dateKeySchema,
});

export const deductionInputSchema = z.object({
  category: z.enum(DEDUCTION_CATEGORIES.map((c) => c.value) as [string, ...string[]], { error: "Choose a deduction type" }),
  amount: rupeeAmountSchema,
  description: optionalText(200),
  deductionDate: z.union([dateKeySchema, z.literal("")]).nullable().optional().transform((v) => v || null),
});
export type DeductionInput = z.input<typeof deductionInputSchema>;

export const reopenSchema = z.object({ reason: z.string().trim().min(1, { error: "Say why you are reopening it" }).max(200) });

export const debtInputSchema = z.object({
  name: z.string().trim().min(1, { error: "Name is required" }).max(120),
  lender: z.string().trim().min(1, { error: "Who did you borrow from?" }).max(120),
  originalAmount: rupeeAmountSchema,
  borrowedOn: dateKeySchema,
  notes: optionalText(1000),
  addToBalance: z.boolean().optional().default(false),
});
export const debtUpdateSchema = z
  .object({
    name: z.string().trim().min(1).max(120),
    lender: z.string().trim().min(1).max(120),
    originalAmount: rupeeAmountSchema,
    borrowedOn: dateKeySchema,
    notes: z.string().trim().max(1000),
  })
  .partial();

export const debtPaymentInputSchema = z.object({
  amount: rupeeAmountSchema,
  paymentDate: dateKeySchema,
  notes: optionalText(500),
  requestId: requestIdSchema,
});

const incomeValues = INCOME_CATEGORIES.map((c) => c.value) as string[];
const expenseValues = EXPENSE_CATEGORIES.map((c) => c.value) as string[];

export const entryInputSchema = z
  .object({
    type: z.enum(["income", "expense"]),
    category: z.string(),
    amount: rupeeAmountSchema,
    date: dateKeySchema,
    description: optionalText(200),
    requestId: requestIdSchema,
  })
  .refine((v) => (v.type === "income" ? incomeValues : expenseValues).includes(v.category), {
    error: "Choose a category",
    path: ["category"],
  });
export type EntryInput = z.infer<typeof entryInputSchema>;

export const reverseSchema = z.object({ reason: optionalText(200) });

export const ledgerFilterSchema = z.object({
  from: dateKeySchema.optional(),
  to: dateKeySchema.optional(),
  direction: z.enum(["in", "out"]).optional(),
  category: z.string().max(40).optional(),
  showReversed: z.enum(["1", "0"]).optional(),
});
